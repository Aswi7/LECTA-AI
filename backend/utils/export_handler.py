def set_cell_background(cell, hex_color):
    """Sets background shading of a DOCX table cell."""
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_color)
    tcPr.append(shd)

def set_cell_margins(cell, top=140, bottom=140, left=200, right=200):
    """Sets cell padding (margins) of a DOCX table cell in twentieths of a point (dxa)."""
    tcPr = cell._tc.get_or_add_tcPr()
    tcMar = OxmlElement('w:tcMar')
    for margin_name, val in [('w:top', top), ('w:bottom', bottom), ('w:left', left), ('w:right', right)]:
        node = OxmlElement(margin_name)
        node.set(qn('w:w'), str(val))
        node.set(qn('w:type'), 'dxa')
        tcMar.append(node)
    tcPr.append(tcMar)


def export_as_docx(session_data: Dict[str, Any], output_path: str) -> str:
    """Generates a structured, premium styled Word document (DOCX)."""
    logger.info(f"Generating DOCX for session {session_data.get('session_id')} at {output_path}")
    
    doc = Document()
    
    # Configure page margins to 1 inch all around
    for section in doc.sections:
        section.top_margin = Inches(1.0)
        section.bottom_margin = Inches(1.0)
        section.left_margin = Inches(1.0)
        section.right_margin = Inches(1.0)
        
    # Set default Normal font style
    normal_style = doc.styles['Normal']
    normal_font = normal_style.font
    normal_font.name = 'Segoe UI'
    normal_font.size = Pt(10.5)
    normal_font.color.rgb = RGBColor(15, 23, 42) # Slate 900
    
    # Modern Title Block
    title_para = doc.add_paragraph()
    title_run = title_para.add_run("LECTA AI — Lecture Notes")
    title_run.font.name = 'Segoe UI Semibold'
    title_run.font.size = Pt(20)
    title_run.font.bold = True
    title_run.font.color.rgb = RGBColor(79, 70, 229) # Indigo 600
    title_para.paragraph_format.space_after = Pt(12)
    
    filename = session_data.get('filename', 'Unknown')
    gen_date = datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S")
    detected_lang = session_data.get('language', {}).get('name', 'Not available')
    target_lang_code = session_data.get('target_language')
    target_lang = LANGUAGES_MAP.get(target_lang_code, target_lang_code).upper() if target_lang_code else 'Not available'
    session_id = session_data.get('session_id', 'N/A')
    
    # Metadata Box (Borderless Table)
    meta_table = doc.add_table(rows=3, cols=2)
    meta_table.autofit = True
    
    fields_left = [
        ("File Name:", filename),
        ("Generated:", gen_date),
        ("Session ID:", session_id)
    ]
    fields_right = [
        ("Detected Language:", detected_lang),
        ("Target Language:", target_lang),
        ("", "")
    ]
    
    for i, (lbl, val) in enumerate(fields_left):
        cell = meta_table.rows[i].cells[0]
        p = cell.paragraphs[0]
        run_lbl = p.add_run(lbl + " ")
        run_lbl.bold = True
        run_lbl.font.size = Pt(9)
        run_lbl.font.color.rgb = RGBColor(71, 85, 105)
        run_val = p.add_run(val)
        run_val.font.size = Pt(9)
        run_val.font.color.rgb = RGBColor(71, 85, 105)
        
    for i, (lbl, val) in enumerate(fields_right):
        if not lbl:
            continue
        cell = meta_table.rows[i].cells[1]
        p = cell.paragraphs[0]
        run_lbl = p.add_run(lbl + " ")
        run_lbl.bold = True
        run_lbl.font.size = Pt(9)
        run_lbl.font.color.rgb = RGBColor(71, 85, 105)
        run_val = p.add_run(val)
        run_val.font.size = Pt(9)
        run_val.font.color.rgb = RGBColor(71, 85, 105)
        
    # Spacer
    spacer = doc.add_paragraph()
    spacer.paragraph_format.space_before = Pt(8)
    
    # Custom Heading builder
    def add_custom_heading(text, level=1):
        p = doc.add_paragraph()
        run = p.add_run(text)
        run.bold = True
        if level == 1:
            run.font.size = Pt(14)
            run.font.color.rgb = RGBColor(15, 23, 42) # Slate 900
            p.paragraph_format.space_before = Pt(16)
            p.paragraph_format.space_after = Pt(6)
        else:
            run.font.size = Pt(11.5)
            run.font.color.rgb = RGBColor(51, 65, 85) # Slate 700
            p.paragraph_format.space_before = Pt(10)
            p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.keep_with_next = True
        return p
        
    # Helper to add styled callout tables
    def add_callout_box(text, bg_hex):
        tbl = doc.add_table(rows=1, cols=1)
        tbl.alignment = 1 # Center
        cell = tbl.cell(0, 0)
        set_cell_background(cell, bg_hex)
        set_cell_margins(cell, top=140, bottom=140, left=200, right=200)
        p = cell.paragraphs[0]
        run = p.add_run(text)
        run.font.size = Pt(10)
        p.paragraph_format.space_after = Pt(0)
        # Spacer paragraph after
        spacer = doc.add_paragraph()
        spacer.paragraph_format.space_before = Pt(4)

    # Summary
    add_custom_heading("Summary", level=1)
    add_callout_box(session_data.get('summary') or "Not available", "F8FAFC")
    
    # Key Points
    add_custom_heading("Key Points", level=1)
    bullet_notes = session_data.get('bullet_notes')
    if bullet_notes:
        for note in bullet_notes:
            cleaned_note = note.replace('• ', '').strip()
            p = doc.add_paragraph(style='List Bullet')
            run = p.add_run(cleaned_note)
            p.paragraph_format.space_after = Pt(4)
    else:
        doc.add_paragraph("Not available")
        

        
    # Translation
    add_custom_heading(f"Translation ({target_lang})", level=1)
    add_callout_box(session_data.get('translated_content') or "Not available", "F5F3FF")
    
    # Exam Questions
    add_custom_heading("Exam Questions & Answers", level=1)
    questions = session_data.get('questions', [])
    if questions:
        q_types = {'definition': 'Definitions', 'fill_blank': 'Fill in the Blanks', 'true_false': 'True or False'}
        for q_type, q_label in q_types.items():
            type_qs = [q for q in questions if q['type'] == q_type]
