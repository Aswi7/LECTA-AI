# Register Unicode fonts for ReportLab if running on Windows
def register_unicode_fonts():
    font_name = 'Helvetica'
    bold_font_name = 'Helvetica-Bold'
    
    font_path = r"C:\Windows\Fonts\Nirmala.ttc"
    if os.path.exists(font_path):
        try:
            from reportlab.pdfbase import pdfmetrics
            from reportlab.pdfbase.ttfonts import TTFont
            # Attempt to register proper Regular (index 0) and Bold (index 1) sub-fonts
            try:
                pdfmetrics.registerFont(TTFont('Nirmala', font_path, subfontIndex=0))
                pdfmetrics.registerFont(TTFont('Nirmala-Bold', font_path, subfontIndex=1))
            except Exception as ttc_err:
                logger.warning(f"Could not load TTC indices, loading default: {ttc_err}")
                pdfmetrics.registerFont(TTFont('Nirmala', font_path))
                pdfmetrics.registerFont(TTFont('Nirmala-Bold', font_path))
            font_name = 'Nirmala'
            bold_font_name = 'Nirmala-Bold'
        except Exception as e:
            logger.warning(f"Error registering Nirmala font for PDF: {e}")
            
    return font_name, bold_font_name


class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas to dynamically compute and print 'Page X of Y' footers."""
    def __init__(self, *args, **kwargs):
        canvas.Canvas.__init__(self, *args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_decorations(self, page_count):
        self.saveState()
        
        # Check if Unicode font is registered
        font_name = 'Helvetica'
        try:
            from reportlab.pdfbase import pdfmetrics
            if 'Nirmala' in pdfmetrics.getRegisteredFontNames():
                font_name = 'Nirmala'
        except:
            pass
            
        self.setFont(font_name, 8)
        self.setFillColor(HexColor("#64748B")) # Slate-500
        
        # Draw running header on page 2 and later
        if self._pageNumber > 1:
            self.drawString(54, 755, "LECTA AI — Lecture Notes")
            self.setStrokeColor(HexColor("#E2E8F0")) # Slate-200 divider
            self.setLineWidth(0.5)
            self.line(54, 750, 612 - 54, 750)
            
        # Draw running footer line and info on all pages
        self.setStrokeColor(HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(54, 50, 612 - 54, 50)
        
        self.drawString(54, 38, "Generated by LECTA AI")
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(612 - 54, 38, page_text)
        
        self.restoreState()


